/** Read the server's translations off a host element's data-i18n, falling back to English. */
export function labelsFromElement(el) {
    try {
        const raw = el?.dataset?.i18n;
        if (raw) return { ...DEFAULT_LABELS, ...JSON.parse(raw) };
    } catch { /* fall through */ }
    return DEFAULT_LABELS;
}
